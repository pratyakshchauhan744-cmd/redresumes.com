export const getResumeExamplePreset = (identifier: string): ResumeExamplePreset | undefined => {
  if (!identifier) return undefined;
  const trimmed = identifier.trim();

  // 1. Check exact key
  if (resumeExamplePresets[trimmed]) {
    return resumeExamplePresets[trimmed];
  }

  // 2. Check case-insensitive key
  const matchKey = Object.keys(resumeExamplePresets).find(
    (k) => k.toLowerCase() === trimmed.toLowerCase()
  );
  if (matchKey && resumeExamplePresets[matchKey]) {
    return resumeExamplePresets[matchKey];
  }

  // 3. Check role guide slug matching
  const matchedGuide = roleGuides.find(
    (g) => g.slug === trimmed.toLowerCase() || g.role.toLowerCase() === trimmed.toLowerCase()
  );
  if (matchedGuide) {
    const ex = matchedGuide.resumeExample;
    return {
      templateId: ex.templateId,
      fullName: ex.name,
      jobTitle: ex.jobTitle,
      email: ex.email,
      phone: ex.phone,
      location: ex.location,
      profileLink: ex.profileLink || '',
      summary: ex.summary,
      experiences: ex.experience.map((e) => ({
        title: `${e.title} - ${e.company}${e.location ? `, ${e.location}` : ''}`,
        dates: e.dates,
        bullets: e.bullets.join('\n'),
      })),
      skillsInput: ex.skills.join(', '),
      educationDegree: ex.education[0]?.degree || '',
      educationSchool: ex.education[0]?.school || '',
      educationYear: ex.education[0]?.year || '',
      projectsInput: ex.projects?.map((p) => `${p.title}: ${p.description}`).join('\n') || '',
      certificationsInput: ex.certifications?.join(', ') || '',
      languagesInput: ex.languages?.join(', ') || '',
      achievementsInput: '',
    };
  }

  return undefined;
};
